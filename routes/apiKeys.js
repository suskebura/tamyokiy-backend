// ============================================================
// 🆕 CREATE API KEY (User - create their own key)
// ============================================================
router.post('/', auth, async (req, res) => {
    try {
        const {
            name,
            permissions,
            rateLimit,
            expiresAt,
            ipWhitelist,
            description
        } = req.body;

        if (!name) {
            return res.status(400).json({
                success: false,
                message: 'Name is required'
            });
        }

        // Check if user already has too many keys (max 5)
        const keyCount = await ApiKey.countDocuments({ 
            userId: req.user._id,
            isActive: true 
        });
        
        if (keyCount >= 5) {
            return res.status(400).json({
                success: false,
                message: 'Maximum 5 active API keys allowed per user'
            });
        }

        // Create new API key (key will be auto-generated by pre-save hook)
        const apiKey = new ApiKey({
            userId: req.user._id,
            name: name.trim(),
            permissions: permissions || {
                shipments: { create: true, read: true, update: true, delete: false },
                tracking: { read: true },
                webhooks: { manage: true },
                drivers: { read: true },
                rates: { read: true }
            },
            rateLimit: rateLimit || { 
                requestsPerMinute: 60, 
                requestsPerDay: 10000 
            },
            expiresAt: expiresAt ? new Date(expiresAt) : null,
            ipWhitelist: ipWhitelist || [],
            description: description || '',
            isActive: true
        });

        await apiKey.save();

        // Log creation
        console.log('🔑 API Key created for user:', req.user.email);

        // Return the key (only shown once on creation)
        res.status(201).json({
            success: true,
            data: {
                _id: apiKey._id,
                name: apiKey.name,
                key: apiKey.key, // ⚠️ Show the actual key only on creation
                permissions: apiKey.permissions,
                rateLimit: apiKey.rateLimit,
                isActive: apiKey.isActive,
                expiresAt: apiKey.expiresAt,
                ipWhitelist: apiKey.ipWhitelist,
                description: apiKey.description,
                createdAt: apiKey.createdAt,
                maskedKey: apiKey.maskedKey
            },
            message: '⚠️ Save this API key now. It will not be shown again!'
        });

    } catch (err) {
        console.error('❌ Create API Key error:', err);
        res.status(500).json({ 
            success: false, 
            message: err.message 
        });
    }
});

// ============================================================
// ✏️ UPDATE API KEY (User - update their own key)
// ============================================================
router.put('/:id', auth, async (req, res) => {
    try {
        const { 
            name, 
            permissions, 
            rateLimit, 
            isActive, 
            expiresAt, 
            ipWhitelist, 
            description 
        } = req.body;

        const apiKey = await ApiKey.findOne({
            _id: req.params.id,
            userId: req.user._id
        });

        if (!apiKey) {
            return res.status(404).json({
                success: false,
                message: 'API Key not found'
            });
        }

        // Update fields
        if (name) apiKey.name = name.trim();
        if (permissions) apiKey.permissions = permissions;
        if (rateLimit) apiKey.rateLimit = rateLimit;
        if (isActive !== undefined) apiKey.isActive = isActive;
        if (expiresAt) apiKey.expiresAt = new Date(expiresAt);
        if (ipWhitelist) apiKey.ipWhitelist = ipWhitelist;
        if (description !== undefined) apiKey.description = description;

        apiKey.updatedAt = new Date();
        await apiKey.save();

        res.json({
            success: true,
            data: {
                _id: apiKey._id,
                name: apiKey.name,
                permissions: apiKey.permissions,
                rateLimit: apiKey.rateLimit,
                isActive: apiKey.isActive,
                expiresAt: apiKey.expiresAt,
                ipWhitelist: apiKey.ipWhitelist,
                description: apiKey.description,
                updatedAt: apiKey.updatedAt,
                maskedKey: apiKey.maskedKey
            },
            message: 'API Key updated successfully'
        });

    } catch (err) {
        console.error('❌ Update API Key error:', err);
        res.status(500).json({ 
            success: false, 
            message: err.message 
        });
    }
});

