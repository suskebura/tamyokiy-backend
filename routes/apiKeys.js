// 📊 GET API KEY STATS (User - see their key usage)
// ============================================================
router.get('/:id/stats', auth, async (req, res) => {
    try {
        const apiKey = await ApiKey.findOne({
            _id: req.params.id,
            userId: req.user._id
        });

        if (!apiKey) {
            return res.status(404).json({
                success: false,
                message: 'API Key not found'
            });
        }

        // Get usage stats from logs
        const WebhookLog = mongoose.model('WebhookLog');
        const usageCount = await WebhookLog.countDocuments({
            'payload.apiKeyId': apiKey._id
        });

        res.json({
            success: true,
            data: {
                name: apiKey.name,
                isActive: apiKey.isActive,
                lastUsed: apiKey.lastUsed,
                createdAt: apiKey.createdAt,
                expiresAt: apiKey.expiresAt,
                usageCount: usageCount,
                maskedKey: apiKey.maskedKey
            }
        });

    } catch (err) {
        console.error('❌ Get API Key stats error:', err);
        res.status(500).json({ 
            success: false, 
            message: err.message 
        });
    }
});

