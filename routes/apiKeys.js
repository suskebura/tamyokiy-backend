// 🔄 REGENERATE API KEY (User - regenerate their own key)
// ============================================================
router.post('/:id/regenerate', auth, async (req, res) => {
    try {
        const crypto = require('crypto');
        
        const apiKey = await ApiKey.findOne({
            _id: req.params.id,
            userId: req.user._id
        });

        if (!apiKey) {
            return res.status(404).json({
                success: false,
                message: 'API Key not found'
            });
        }

        // Generate new key
        const oldKey = apiKey.key;
        apiKey.key = `tam_${crypto.randomBytes(32).toString('hex')}`;
        apiKey.lastUsed = null;
        apiKey.updatedAt = new Date();
        await apiKey.save();

        // Log regeneration
        console.log('🔄 API Key regenerated for user:', req.user.email);

        res.json({
            success: true,
            data: {
                _id: apiKey._id,
                key: apiKey.key, // ⚠️ Show new key only on regeneration
                name: apiKey.name,
                maskedKey: apiKey.maskedKey,
                regeneratedAt: apiKey.updatedAt
            },
            message: '⚠️ API Key regenerated successfully. Save this new key now!'
        });

    } catch (err) {
        console.error('❌ Regenerate API Key error:', err);
        res.status(500).json({ 
            success: false, 
            message: err.message 
        });
    }
});

